const {chromium}=require(process.env.CRUMB_PLAYWRIGHT || 'playwright');
const path=require('node:path'),{pathToFileURL}=require('node:url'),assert=require('node:assert/strict');
(async()=>{
 const browser=await chromium.launch({headless:true,executablePath:process.env.CRUMB_BROWSER || 'C:/Program Files/Google/Chrome/Application/chrome.exe'});
 try{
  const page=await browser.newPage({viewport:{width:390,height:844}});
  let accept=false,dialogs=0;const errors=[];
  page.on('dialog',async d=>{dialogs++;assert.match(d.message(),/nest|pile/i);await (accept?d.accept():d.dismiss());});
  page.on('pageerror',e=>errors.push(e.message));
  await page.goto(pathToFileURL(path.join(__dirname,'..','index.html')).href);
  await page.evaluate(()=>{localStorage.clear();localStorage.setItem('crumb.language.v1','en');});await page.reload();
  await page.evaluate(()=>{for(const word of ['moss','thread']){giveWord(word);for(let i=0;i<1500;i++)update(.02);}save();});
  const previous=await page.evaluate(()=>treasures.map(t=>({id:t.id,text:t.text,settled:t.settled})));
  assert.equal(previous.length,2);assert.ok(previous.every(t=>t.settled));
  const notes=await page.evaluate(()=>localStorage.getItem('crumb.discoveries.v1'));
  const rewards=await page.evaluate(()=>localStorage.getItem('crumb.sandbox.v1'));
  await page.locator('#fresh').click();
  assert.equal(dialogs,1);assert.equal(await page.evaluate(()=>treasures.length),2,'cancel preserves nest');
  assert.equal(await page.evaluate(()=>localStorage.getItem('crumb.nest.undo.v1')),null);
  accept=true;await page.locator('#fresh').click();
  assert.equal(await page.evaluate(()=>treasures.length),0);
  assert.ok(await page.locator('#nestUndo').isVisible());
  const backup=await page.evaluate(()=>localStorage.getItem('crumb.nest.undo.v1'));
  await page.locator('#fresh').click();
  assert.equal(await page.evaluate(()=>localStorage.getItem('crumb.nest.undo.v1')),backup,'empty cleanup retains prior undo');
  await page.reload();assert.ok(await page.locator('#nestUndo').isVisible());
  await page.locator('#nestUndo').click();
  assert.deepEqual(await page.evaluate(()=>treasures.map(t=>({id:t.id,text:t.text,settled:t.settled}))),previous);
  assert.equal(await page.evaluate(()=>localStorage.getItem('crumb.discoveries.v1')),notes);
  assert.equal(await page.evaluate(()=>localStorage.getItem('crumb.sandbox.v1')),rewards);
  assert.equal(await page.evaluate(()=>localStorage.getItem('crumb.nest.undo.v1')),null);
  await page.reload();assert.equal(await page.evaluate(()=>treasures.length),2,'restored nest persists');
  await page.locator('#fresh').click();
  await page.evaluate(()=>giveWord('apple'));
  accept=false;await page.locator('#nestUndo').click();
  assert.ok(await page.evaluate(()=>treasures.some(t=>t.text==='apple')),'cancel restore preserves current cards');
  accept=true;await page.locator('#nestUndo').click();
  assert.deepEqual(await page.evaluate(()=>treasures.map(t=>({id:t.id,text:t.text,settled:t.settled}))),previous);
  await page.locator('#fresh').click();
  const rewardsBeforeRebuild=await page.evaluate(()=>localStorage.getItem('crumb.sandbox.v1'));
  await page.evaluate(()=>discover({text:'cookie',kind:'food'}));
  await page.locator('#journalToggle').click();
  await page.locator('#rebuildNestFromNotes').click();
  assert.deepEqual(await page.evaluate(()=>treasures.filter(t=>t.settled).map(t=>t.text).sort()),['moss','thread'],'rebuild only recorded nesting materials');
  assert.equal(await page.evaluate(()=>localStorage.getItem('crumb.sandbox.v1')),rewardsBeforeRebuild,'rebuild keeps rewards');
  await page.reload();assert.equal(await page.evaluate(()=>treasures.filter(t=>t.settled).length),2,'rebuilt pile persists');
  await page.evaluate(()=>{const set=Storage.prototype.setItem;Storage.prototype.setItem=function(k,v){if(k==='crumb.nest.undo.v1')throw Error('Storage unavailable');return set.call(this,k,v);};});
  await page.locator('#fresh').click();
  assert.equal(await page.evaluate(()=>treasures.length),2,'failed backup prevents clearing');
  assert.match(await page.locator('#message').innerText(),/not been cleared/);
  assert.deepEqual(errors,[]);
  console.log('PASS fresh nest: confirmation, cancel, saved undo after reload, restored save, rewards/notes intact, replacement confirmation, empty cleanup, failed backup protection');
 }finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
